import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const run = promisify(execFile);

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDir, "..");
const repoRoot = path.resolve(webRoot, "..");

const cssDir = path.join(webRoot, "static", "assets");
const cssTempPath = path.join(cssDir, "app.css");
const jsSourceDir = path.join(webRoot, "src", "js");
const jsDir = path.join(webRoot, "static", "js");
const fontSourceDir = path.join(webRoot, "src", "fonts");
const fontDir = path.join(webRoot, "static", "fonts");
const generatedGoPath = path.join(repoRoot, "internal", "staticassets", "assets_generated.go");

const fonts = [
	["space-grotesk-latin-500.woff2", "SpaceGrotesk500FontPath"],
	["space-grotesk-latin-700.woff2", "SpaceGrotesk700FontPath"],
	["inter-latin-400.woff2", "Inter400FontPath"],
	["inter-latin-500.woff2", "Inter500FontPath"],
	["inter-latin-700.woff2", "Inter700FontPath"],
];

const scripts = [
	["enhance.js", "EnhanceJSPath"],
	["admin-product-upload.js", "AdminProductUploadJSPath"],
	["admin-dashboard.js", "AdminDashboardJSPath"],
];

function fingerprint(buffer) {
	return createHash("sha256").update(buffer).digest("hex").slice(0, 12);
}

async function removeMatching(dir, pattern) {
	await mkdir(dir, { recursive: true });
	for (const entry of await readdir(dir)) {
		if (pattern.test(entry)) {
			await rm(path.join(dir, entry), { force: true });
		}
	}
}

async function fingerprintFile({ sourcePath, outputDir, basename, extension, cleanPattern, removeSource = false }) {
	const contents = await readFile(sourcePath);
	const filename = await fingerprintBuffer({ contents, outputDir, basename, extension, cleanPattern });
	if (removeSource) {
		await rm(sourcePath, { force: true });
	}
	return filename;
}

async function fingerprintBuffer({ contents, outputDir, basename, extension, cleanPattern }) {
	const hash = fingerprint(contents);
	const filename = `${basename}.${hash}.${extension}`;
	await removeMatching(outputDir, cleanPattern);
	await writeFile(path.join(outputDir, filename), contents);
	return filename;
}

const fontPaths = new Map();
for (const [filename, constName] of fonts) {
	const extension = path.extname(filename).slice(1);
	const basename = path.basename(filename, `.${extension}`);
	const hashedFilename = await fingerprintFile({
		sourcePath: path.join(fontSourceDir, filename),
		outputDir: fontDir,
		basename,
		extension,
		cleanPattern: new RegExp(`^${basename}\\.[a-f0-9]{12}\\.${extension}$`),
	});
	fontPaths.set(constName, `/static/fonts/${hashedFilename}`);
}

let cssContents = await readFile(cssTempPath, "utf8");
for (const [filename, constName] of fonts) {
	cssContents = cssContents.replaceAll(`/static/fonts/${filename}`, fontPaths.get(constName));
}
const cssFilename = await fingerprintBuffer({
	contents: Buffer.from(cssContents),
	outputDir: cssDir,
	basename: "app",
	extension: "css",
	cleanPattern: /^app\.[a-f0-9]{12}\.css$/,
});
await rm(cssTempPath, { force: true });

const scriptPaths = new Map();
for (const [filename, constName] of scripts) {
	const extension = path.extname(filename).slice(1);
	const basename = path.basename(filename, `.${extension}`);
	const hashedFilename = await fingerprintFile({
		sourcePath: path.join(jsSourceDir, filename),
		outputDir: jsDir,
		basename,
		extension,
		cleanPattern: new RegExp(`^${basename}\\.[a-f0-9]{12}\\.${extension}$`),
	});
	scriptPaths.set(constName, `/static/js/${hashedFilename}`);
}

const appCSSPath = `/static/assets/${cssFilename}`;
const generatedConstants = [
	["AppCSSPath", appCSSPath],
	...Array.from(scriptPaths.entries()),
	...Array.from(fontPaths.entries()),
]
	.map(([name, value]) => `\t${name} = ${JSON.stringify(value)}`)
	.join("\n");
const generatedGo = `// Code generated by npm --prefix web run build; DO NOT EDIT.\n\npackage staticassets\n\nconst (\n${generatedConstants}\n)\n`;

await mkdir(path.dirname(generatedGoPath), { recursive: true });
await writeFile(generatedGoPath, generatedGo);
await run("gofmt", ["-w", generatedGoPath]);

console.log(`fingerprinted ${appCSSPath}`);
for (const assetPath of scriptPaths.values()) {
	console.log(`fingerprinted ${assetPath}`);
}
for (const assetPath of fontPaths.values()) {
	console.log(`fingerprinted ${assetPath}`);
}
